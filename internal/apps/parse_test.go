func sorted(list []Package) []Package {
	sort.Slice(list, func(i, j int) bool {
		if list[i].Name != list[j].Name {
			return list[i].Name < list[j].Name
		}
		return list[i].Version < list[j].Version
	})
	return list
}

func TestParseComposerLock(t *testing.T) {
	lock := `{"packages":[{"name":"laravel/framework","version":"v11.31.0"},{"name":"symfony/console","version":"v7.1.6"}],
"packages-dev":[{"name":"phpunit/phpunit","version":"11.4.3"}],"content-hash":"x"}`
	manifest := `{"require":{"php":"^8.2","Laravel/Framework":"^11.0"},"require-dev":{"phpunit/phpunit":"^11.0"},"config":{"http-basic":{"x":{"password":"secret"}}}}`

	got, err := ParseComposerLock([]byte(lock), []byte(manifest))
	if err != nil {
		t.Fatal(err)
	}
	want := []Package{
		{"packagist", "laravel/framework", "11.31.0", true, false},
		{"packagist", "phpunit/phpunit", "11.4.3", true, true},
		{"packagist", "symfony/console", "7.1.6", false, false},
	}
	if !reflect.DeepEqual(sorted(got), want) {
		t.Fatalf("unexpected: %+v", got)
	}

	// composer.json が無くても読む
	if got, err := ParseComposerLock([]byte(lock), nil); err != nil || len(got) != 3 || got[0].Direct {
		t.Fatalf("unexpected: %+v %v", got, err)
	}
	if _, err := ParseComposerLock([]byte("{"), nil); err == nil {
		t.Fatal("expected an error")
	}
}

func TestParsePackageLock(t *testing.T) {
	lock := `{"name":"app","lockfileVersion":3,"packages":{
"":{"name":"app","dependencies":{"vue":"^3.5.0","sw":"npm:string-width@^4.2.0"},"devDependencies":{"vite":"^5.0.0"}},
"node_modules/vue":{"version":"3.5.12"},
"node_modules/@vue/shared":{"version":"3.5.12"},
"node_modules/vite":{"version":"5.4.10","dev":true},
"node_modules/typescript":{"version":"5.6.3","devOptional":true},
"node_modules/vite/node_modules/esbuild":{"version":"0.21.5","dev":true},
"node_modules/sw":{"name":"string-width","version":"4.2.3"},
"node_modules/local-lib":{"resolved":"packages/local-lib","link":true},
"packages/local-lib":{"name":"local-lib","version":"1.0.0"}
}}`
	manifest := ParsePackageJSON([]byte(`{"dependencies":{"vue":"^3.5.0","sw":"npm:string-width@^4.2.0"},"devDependencies":{"vite":"^5.0.0","typescript":"^5.6.0"}}`))

	got, err := ParsePackageLock([]byte(lock), manifest)
	if err != nil {
		t.Fatal(err)
	}
	want := []Package{
		{"npm", "@vue/shared", "3.5.12", false, false},
		{"npm", "esbuild", "0.21.5", false, true},
		{"npm", "string-width", "4.2.3", true, false},
		{"npm", "typescript", "5.6.3", true, true},
		{"npm", "vite", "5.4.10", true, true},
		{"npm", "vue", "3.5.12", true, false},
	}
	if !reflect.DeepEqual(sorted(got), want) {
		t.Fatalf("unexpected: %+v", got)
	}

	// npm 6 までの lockfileVersion 1 は、対応しない
	if _, err := ParsePackageLock([]byte(`{"lockfileVersion":1,"dependencies":{}}`), manifest); !errors.Is(err, errUnsupported) {
		t.Fatalf("expected unsupported: %v", err)
	}
}

