func TestParseWP(t *testing.T) {
	if v := ParseWPVersion([]byte("<?php\n/**\n * @global string $wp_version\n */\n$wp_version = '6.8.1';\n$wp_db_version = 58975;\n")); v != "6.8.1" {
		t.Fatalf("unexpected: %q", v)
	}

	plugin := []byte("<?php\n/**\n * Plugin Name: Contact Form 7\n * Requires PHP: 7.4\n * Version: 6.0.1 */\n")
	if v, ok := ParseWPHeader(plugin, "Version"); !ok || v != "6.0.1" {
		t.Fatalf("unexpected: %q %v", v, ok)
	}
	if _, ok := ParseWPHeader(plugin, "Plugin Name"); !ok {
		t.Fatal("expected Plugin Name")
	}
	// "Requires PHP:" などの、別の見出しの一部は拾わない
	if v, ok := ParseWPHeader([]byte("/*\nTheme Name: X\nTested up to: 6.8\n*/"), "Version"); ok {
		t.Fatalf("unexpected: %q", v)
	}
}

// 名前だけでなく、書かれた範囲・版で直接の依存を決める（同じ名前の別の版は、間接の依存）
func TestDirectByRange(t *testing.T) {
	manifest := ParsePackageJSON([]byte(`{"dependencies":{"express":"^4.21.0","string-width":"^4.2.0"},"devDependencies":{"debug":"^4.3.4"}}`))

	yarn := `# yarn lockfile v1

debug@2.6.9:
  version "2.6.9"

debug@^4.3.4:
  version "4.3.7"

express@^4.21.0:
  version "4.21.1"

"string-width-cjs@npm:string-width@^4.2.0", string-width@^4.2.0:
  version "4.2.3"
`
	got, err := ParseYarnLock([]byte(yarn), manifest)
	if err != nil {
		t.Fatal(err)
	}
	want := []Package{
		{"npm", "debug", "2.6.9", false, false},
		{"npm", "debug", "4.3.7", true, true},
		{"npm", "express", "4.21.1", true, false},
		{"npm", "string-width", "4.2.3", true, false},
	}
	if !reflect.DeepEqual(sorted(got), want) {
		t.Fatalf("yarn: %+v", got)
	}

	pnpm := `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      express:
        specifier: ^4.21.0
        version: 4.21.1
    devDependencies:
      debug:
        specifier: ^4.3.4
        version: 4.3.7

packages:

  debug@2.6.9:
    resolution: {integrity: x}

  debug@4.3.7:
    resolution: {integrity: x}

  express@4.21.1:
    resolution: {integrity: x}
`
	got, err = ParsePnpmLock([]byte(pnpm), manifest)
	if err != nil {
		t.Fatal(err)
	}
	want = want[:3]
	if !reflect.DeepEqual(sorted(got), want) {
		t.Fatalf("pnpm: %+v", got)
	}
}
